create or replace FUNCTION f_check_char
(
    p_value IN VARCHAR2,
    p_type  IN NUMBER
)
RETURN NUMBER
IS
    v_str VARCHAR2(4000);
BEGIN
    v_str := TRIM(p_value);

    -------------------------------------------------------------------
    -- 102 = NAME (Greek + English letters only + space + . - )
    -------------------------------------------------------------------
    IF p_type = 102 and v_str is not null  THEN

        v_str := UPPER(v_str);

        -- Normalize Greek accents
        v_str := REPLACE(v_str, 'Ά','Α');
        v_str := REPLACE(v_str, 'Έ','Ε');
        v_str := REPLACE(v_str, 'Ή','Η');
        v_str := REPLACE(v_str, 'Ί','Ι');
        v_str := REPLACE(v_str, 'Ό','Ο');
        v_str := REPLACE(v_str, 'Ύ','Υ');
        v_str := REPLACE(v_str, 'Ώ','Ω');
        v_str := REPLACE(v_str, 'Ϊ','Ι');
        v_str := REPLACE(v_str, 'Ϋ','Υ');

        IF NOT REGEXP_LIKE(v_str, '^[A-ZΑ-Ω .-]+$') THEN
            RETURN 1;
        END IF;

    -------------------------------------------------------------------
    -- 103 = PHONE (numbers only)
    -------------------------------------------------------------------
    ELSIF p_type = 103 and v_str is not null THEN

        IF NOT REGEXP_LIKE(v_str, '^[0-9]+$') THEN
            RETURN 1;
        END IF;
    -------------------------------------------------------------------
    -- 104 = EMAIL
    -------------------------------------------------------------------
    ELSIF p_type = 104 and v_str is not null  THEN
    IF NOT REGEXP_LIKE(v_str,
       '^[A-Za-z0-9._%+-]+@(go\.uop\.gr|uop\.gr|GO\.UOP\.GR|UOP\.GR)$')
    THEN
        RETURN 1;
    END IF;

    ELSIF p_type = 105 and v_str is not null THEN
        IF LENGTH(v_str) <= 5 THEN
            RETURN 1;
    END IF;
    -------------------------------------------------------------------
    -- UNKNOWN TYPE
    -------------------------------------------------------------------
    ELSE
        RETURN 0;
    END IF;

    RETURN 0; -- VALID

END f_check_char;
/
