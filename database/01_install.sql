create or replace function auth_user_credentials(p_username IN VARCHAR2, p_password IN VARCHAR2)
  return boolean
is
  l_count number;
begin
  select count(id)
    into l_count
    from user_credentials
   where upper(username) = upper(p_username)
     and password = p_password;

  if l_count = 1 then
    return true;
  else
    return false;
  end if;

exception
  when others then
    return false;
end;
