                         103         Στοιχεία Επικοινωνίας(Email και Τηλέφωνο)
                         104         Δικαίωμα Διαχειριστή
                         105         Κατάσταση Χρήστη
                         106         Τύπος Χρήστη(Καθηγητής ή Φοιτητής)
                         107         Ονομασία Συναλλασσομένου + Τύπος(Καθηγητής, Φοιτητής κλπ)
   */

   vresult         VARCHAR2(4000 CHAR);
   begin
        IF celt = 101 THEN 
            SELECT name||' '||surname
            INTO vresult
            FROM users
            WHERE id = userID;
        elsif celt = 102 THEN 
            select f_clv_descr(university_id)||' ('||f_clv_descr(department_id)||')'
            INTO vresult
            FROM user_details 
            WHERE user_id = userID;
        elsif celt = 103 THEN 
            select case when phone is not null then 
                    email||' - ('||phone||')'
                    else
                        email
                    end as info
            INTO vresult
            FROM user_details
            WHERE user_id = userID;
        elsif celt = 104 THEN 
            SELECT isAdmin
            INTO vresult
            FROM users
            WHERE id = userID;
        elsif celt = 105 THEN 
            SELECT active
            INTO vresult
            FROM users
            WHERE id = userID;
        elsif celt = 106 THEN 
            SELECT decode(role_id, 'ROLE:1', 'stud', 'ROLE:2', 'prof')
            INTO vresult
            FROM users
            WHERE id = userID;
        elsif celt = 107 THEN 
            SELECT name||' '||surname||' ('||f_clv_descr(type_id)||')'
            INTO vresult
            FROM users
            WHERE id = userID;
        end if;
        return vresult;
        exception when others then
            vresult := null;        
   end;
/












































